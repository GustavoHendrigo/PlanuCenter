function mapCliente(row) {
  return {
    id: row.id,
    nome: row.nome,
    email: row.email ?? undefined,
    telefone: row.telefone ?? undefined
  };
}

function mapVeiculo(row) {
  return {
    id: row.id,
    placa: row.placa,
    marca: row.marca,
    modelo: row.modelo,
    ano: row.ano,
    clienteId: row.clienteId,
    clienteNome: row.clienteNome ?? 'Cliente não encontrado'
  };
}

function mapPeca(row) {
  return {
    id: row.id,
    nome: row.nome,
    codigo: row.codigo,
    estoque: Number(row.estoque),
    preco: Number(row.preco)
  };
}

function mapServico(row) {
  return {
    id: row.id,
    descricao: row.descricao,
    preco: Number(row.preco)
  };
}

function mapOrdemServico(row) {
  return {
    id: row.id,
    clienteId: row.clienteId,
    veiculoId: row.veiculoId,
    dataEntrada: row.dataEntrada,
    status: row.status,
    servicos: row.servicos ?? [],
    pecas: row.pecas ?? [],
    observacoes: row.observacoes ?? undefined
  };
}

async function getClientes() {
  const { rows } = await pool.query('SELECT id, nome, email, telefone FROM clientes ORDER BY id ASC');
  return rows.map(mapCliente);
}

async function addCliente(cliente) {
  const { rows } = await pool.query(
    'INSERT INTO clientes (nome, email, telefone) VALUES ($1, $2, $3) RETURNING id, nome, email, telefone',
    [cliente.nome, cliente.email ?? null, cliente.telefone ?? null]
  );
  return mapCliente(rows[0]);
}

async function updateCliente(id, updates) {
  const { rows } = await pool.query(
    'UPDATE clientes SET nome = $1, email = $2, telefone = $3 WHERE id = $4 RETURNING id, nome, email, telefone',
    [updates.nome, updates.email ?? null, updates.telefone ?? null, id]
  );
  return rows[0] ? mapCliente(rows[0]) : null;
}

async function getVeiculos() {
  const { rows } = await pool.query(`
    SELECT
      v.id,
      v.placa,
      v.marca,
      v.modelo,
      v.ano,
      v.cliente_id AS "clienteId",
      c.nome AS "clienteNome"
    FROM veiculos v
    LEFT JOIN clientes c ON c.id = v.cliente_id
    ORDER BY v.id ASC
  `);
  return rows.map(mapVeiculo);
}

async function addVeiculo(veiculo) {
  const insertResult = await pool.query(
    'INSERT INTO veiculos (placa, marca, modelo, ano, cliente_id) VALUES ($1, $2, $3, $4, $5) RETURNING id',
    [veiculo.placa, veiculo.marca, veiculo.modelo, veiculo.ano, veiculo.clienteId]
  );
  return (await getVeiculoById(insertResult.rows[0].id)) ?? null;
}

async function updateVeiculo(id, updates) {
  const { rowCount } = await pool.query(
    'UPDATE veiculos SET placa = $1, marca = $2, modelo = $3, ano = $4, cliente_id = $5 WHERE id = $6',
    [updates.placa, updates.marca, updates.modelo, updates.ano, updates.clienteId, id]
  );
  if (!rowCount) {
    return null;
  }
  return (await getVeiculoById(id)) ?? null;
}

async function getVeiculoById(id) {
  const { rows } = await pool.query(
    `SELECT v.id, v.placa, v.marca, v.modelo, v.ano, v.cliente_id AS "clienteId", c.nome AS "clienteNome"
     FROM veiculos v
     LEFT JOIN clientes c ON c.id = v.cliente_id
     WHERE v.id = $1`,
    [id]
  );
  return rows[0] ? mapVeiculo(rows[0]) : null;
}

