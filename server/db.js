const pool = new Pool({
  connectionString: process.env.DATABASE_URL,
  host: process.env.PGHOST,
  port: process.env.PGPORT ? Number(process.env.PGPORT) : undefined,
  database: process.env.PGDATABASE,
  user: process.env.PGUSER,
  password: process.env.PGPASSWORD,
  ssl: process.env.PGSSLMODE === 'require' ? { rejectUnauthorized: false } : undefined
});

async function initializeDatabase() {
  await pool.query(`
    CREATE TABLE IF NOT EXISTS clientes (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      nome TEXT NOT NULL,
      email TEXT,
      telefone TEXT
    );

    CREATE TABLE IF NOT EXISTS veiculos (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      placa TEXT NOT NULL UNIQUE,
      marca TEXT NOT NULL,
      modelo TEXT NOT NULL,
      ano TEXT NOT NULL,
      cliente_id INTEGER NOT NULL REFERENCES clientes(id) ON DELETE CASCADE
    );

    CREATE TABLE IF NOT EXISTS pecas (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      nome TEXT NOT NULL,
      codigo TEXT NOT NULL,
      estoque INTEGER NOT NULL,
      preco NUMERIC(12, 2) NOT NULL
    );

    CREATE UNIQUE INDEX IF NOT EXISTS pecas_codigo_idx ON pecas(codigo);

    CREATE TABLE IF NOT EXISTS servicos (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      descricao TEXT NOT NULL,
      preco NUMERIC(12, 2) NOT NULL
    );

    CREATE TABLE IF NOT EXISTS ordens_servico (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      cliente_id INTEGER NOT NULL REFERENCES clientes(id) ON DELETE CASCADE,
      veiculo_id INTEGER NOT NULL REFERENCES veiculos(id) ON DELETE CASCADE,
      data_entrada DATE NOT NULL,
      status TEXT NOT NULL,
      servicos JSONB NOT NULL DEFAULT '[]'::jsonb,
      pecas JSONB NOT NULL DEFAULT '[]'::jsonb,
      observacoes TEXT
    );
  `);

  await seedDefaults();
}

async function seedDefaults() {
  await seedTable('clientes', defaultData.clientes, row =>
    pool.query(
      'INSERT INTO clientes (id, nome, email, telefone) VALUES ($1, $2, $3, $4) ON CONFLICT (id) DO NOTHING',
      [row.id, row.nome, row.email ?? null, row.telefone ?? null]
    )
  );

  await seedTable('veiculos', defaultData.veiculos, row =>
    pool.query(
      'INSERT INTO veiculos (id, placa, marca, modelo, ano, cliente_id) VALUES ($1, $2, $3, $4, $5, $6) ON CONFLICT (id) DO NOTHING',
      [row.id, row.placa, row.marca, row.modelo, row.ano, row.clienteId]
    )
  );

  await seedTable('pecas', defaultData.pecas, row =>
    pool.query(
      'INSERT INTO pecas (id, nome, codigo, estoque, preco) VALUES ($1, $2, $3, $4, $5) ON CONFLICT (id) DO NOTHING',
      [row.id, row.nome, row.codigo, row.estoque, row.preco]
    )
  );

  await seedTable('servicos', defaultData.servicos, row =>
    pool.query(
      'INSERT INTO servicos (id, descricao, preco) VALUES ($1, $2, $3) ON CONFLICT (id) DO NOTHING',
      [row.id, row.descricao, row.preco]
    )
  );

  await seedTable('ordens_servico', defaultData.ordensServico, row =>
    pool.query(
      `INSERT INTO ordens_servico (id, cliente_id, veiculo_id, data_entrada, status, servicos, pecas, observacoes)
       VALUES ($1, $2, $3, $4, $5, $6::jsonb, $7::jsonb, $8)
       ON CONFLICT (id) DO NOTHING`,
      [
        row.id,
        row.clienteId,
        row.veiculoId,
        row.dataEntrada,
        row.status,
        JSON.stringify(row.servicos ?? []),
        JSON.stringify(row.pecas ?? []),
        row.observacoes ?? null
      ]
    )
  );

  await alignSequences();
}

async function seedTable(tableName, rows, insertFn) {
  const { rowCount } = await pool.query(`SELECT 1 FROM ${tableName} LIMIT 1`);
  if (rowCount > 0) {
    return;
  }

  for (const row of rows) {
    await insertFn(row);
  }
}

async function alignSequences() {
  const tables = [
    ['clientes', 'id'],
    ['veiculos', 'id'],
    ['pecas', 'id'],
    ['servicos', 'id'],
    ['ordens_servico', 'id']
  ];

  for (const [table, column] of tables) {
    await pool.query(
      `SELECT setval(pg_get_serial_sequence($1, $2), COALESCE((SELECT MAX(${column}) FROM ${table}), 0))`,
      [table, column]
    );
  }
}

